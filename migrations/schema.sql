--
-- Name: prepare_booking(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.prepare_booking() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  v_role public.app_role;
  v_class_id uuid;
  v_room_capacity integer;
  v_room_active boolean;
  v_now timestamptz := statement_timestamp();
begin
  if new.requester_id is distinct from (select auth.uid()) then
    raise exception 'Requester must be the signed-in user.';
  end if;

  select p.role, p.class_id into v_role, v_class_id
  from public.profiles p
  where p.id = new.requester_id and p.is_active = true;

  if not found or v_role <> 'komting'::public.app_role then
    raise exception 'Only an active komting can submit a booking.';
  end if;
  if new.class_id is distinct from v_class_id then
    raise exception 'Booking class must match the komting class.';
  end if;
  if new.ends_at <= new.starts_at then
    raise exception 'End time must be later than start time.';
  end if;
  if new.starts_at <= v_now then
    raise exception 'Booking start time must be in the future.';
  end if;

  select r.capacity, r.is_active into v_room_capacity, v_room_active
  from public.rooms r where r.id = new.room_id;
  if not found or v_room_active = false then
    raise exception 'Room does not exist or is inactive.';
  end if;
  if new.participant_count is not null and new.participant_count > v_room_capacity then
    raise exception 'Participant count exceeds room capacity.';
  end if;

  new.rejection_reason := null;
  new.cancellation_reason := null;
  new.decided_by := null;
  new.decided_at := null;
  new.actual_ended_at := null;

  if new.booking_type = 'krs_priority'::public.booking_type then
    new.status := 'pending'::public.booking_status;
  elsif new.starts_at <= v_now + interval '15 minutes' then
    new.booking_type := 'instant'::public.booking_type;
    new.status := 'approved'::public.booking_status;
  else
    new.booking_type := 'regular'::public.booking_type;
    new.status := 'pending'::public.booking_status;
  end if;

  return new;
end;
$$;


--
-- Name: review_registration_request(uuid, text, text); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.review_registration_request(p_request_id uuid, p_decision text, p_rejection_reason text DEFAULT NULL::text) RETURNS jsonb
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  v_actor_id uuid := (select auth.uid());
  v_actor_role public.app_role;
  v_actor_class_id uuid;
  v_actor_active boolean;
  v_request public.registration_requests%rowtype;
  v_class_active boolean;
begin
  if v_actor_id is null then
    raise exception 'Authentication is required.';
  end if;

  if p_decision is null or p_decision not in ('approved', 'rejected') then
    raise exception 'Decision must be approved or rejected.';
  end if;

  if p_decision = 'rejected' and nullif(trim(p_rejection_reason), '') is null then
    raise exception 'A rejection reason is required.';
  end if;

  select rr.* into v_request
  from public.registration_requests rr
  where rr.id = p_request_id
  for update;

  if not found then
    raise exception 'Registration request was not found.';
  end if;

  if v_request.status <> 'pending' then
    raise exception 'This registration request has already been reviewed.';
  end if;

  -- Lock the class row to serialize approval attempts for the same class.
  select c.is_active into v_class_active
  from public.classes c
  where c.id = v_request.class_id
  for update;

  if not found or v_class_active is not true then
    raise exception 'The selected class is inactive or unavailable.';
  end if;

  select p.role, p.class_id, p.is_active
  into v_actor_role, v_actor_class_id, v_actor_active
  from public.profiles p
  where p.id = v_actor_id;

  if not found or v_actor_active is not true then
    raise exception 'Reviewer account is inactive.';
  end if;

  if v_request.requested_role = 'komting' then
    if v_actor_role <> 'admin'::public.app_role then
      raise exception 'Only an Admin can review a Komting registration.';
    end if;

    if p_decision = 'approved' and exists (
      select 1 from public.profiles p
      where p.class_id = v_request.class_id
        and p.role = 'komting'::public.app_role
        and p.is_active = true
    ) then
      raise exception 'This class already has an active Komting.';
    end if;

  elsif v_request.requested_role = 'mahasiswa' then
    if v_actor_role <> 'komting'::public.app_role
       or v_actor_class_id is distinct from v_request.class_id then
      raise exception 'Only the active Komting of the selected class can review this request.';
    end if;
  else
    raise exception 'Unsupported requested role.';
  end if;

  if p_decision = 'approved' then
    update public.profiles
    set role = v_request.requested_role::public.app_role,
        class_id = v_request.class_id,
        is_active = true
    where id = v_request.user_id
      and is_active = false;

    if not found then
      raise exception 'Applicant profile is already active or unavailable.';
    end if;

    update public.registration_requests
    set status = 'approved',
        reviewed_by = v_actor_id,
        reviewed_at = now(),
        rejection_reason = null
    where id = v_request.id;
  else
    -- The profile remains inactive and unassigned after rejection.
    update public.registration_requests
    set status = 'rejected',
        reviewed_by = v_actor_id,
        reviewed_at = now(),
        rejection_reason = trim(p_rejection_reason)
    where id = v_request.id;
  end if;

  return jsonb_build_object(
    'request_id', v_request.id,
    'user_id', v_request.user_id,
