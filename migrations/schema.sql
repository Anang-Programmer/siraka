--
-- Name: handle_new_auth_user(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.handle_new_auth_user() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  v_requested_role text;
  v_class_id uuid;
  v_class_is_active boolean;
  v_name text;
  v_student_number text;
begin
  v_name := coalesce(
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''),
    nullif(btrim(new.raw_user_meta_data ->> 'name'), ''),
    'Pengguna'
  );

  v_requested_role := nullif(btrim(new.raw_user_meta_data ->> 'requested_role'), '');
  v_student_number := nullif(btrim(new.raw_user_meta_data ->> 'student_number'), '');

  -- NIM is required for public self-registration (Mahasiswa or Komting).
  -- Admin/invited accounts without registration metadata may keep it NULL.
  if v_requested_role in ('mahasiswa', 'komting') then
    if v_student_number is null then
      raise exception 'NIM wajib diisi untuk pendaftaran Mahasiswa atau Komting.';
    end if;

    if length(v_student_number) > 30 then
      raise exception 'NIM maksimal 30 karakter.';
    end if;
  end if;

  -- New accounts remain inactive until the proper approver accepts the request.
  insert into public.profiles (
    id, full_name, email, student_number, role, class_id, is_active
  )
  values (
    new.id,
    v_name,
    new.email,
    v_student_number,
    'mahasiswa'::public.app_role,
    null,
    false
  )
  on conflict (id) do update
    set email = excluded.email,
        student_number = coalesce(
          public.profiles.student_number,
          excluded.student_number
        );

  -- Accounts created without a self-registration role are not submitted for approval.
  if v_requested_role is null then
    return new;
  end if;

  if v_requested_role not in ('mahasiswa', 'komting') then
    raise exception 'Registration role must be mahasiswa or komting.';
  end if;

  begin
    v_class_id := nullif(btrim(new.raw_user_meta_data ->> 'requested_class_id'), '')::uuid;
  exception when invalid_text_representation then
    raise exception 'Invalid class selected for registration.';
  end;

  if v_class_id is null then
    raise exception 'A class must be selected during registration.';
  end if;

  select c.is_active into v_class_is_active
  from public.classes c
  where c.id = v_class_id;

  if not found or v_class_is_active is not true then
    raise exception 'Selected class does not exist or is inactive.';
  end if;

  if v_requested_role = 'mahasiswa' and not exists (
    select 1
    from public.profiles p
    where p.class_id = v_class_id
      and p.role = 'komting'::public.app_role
      and p.is_active = true
  ) then
    raise exception 'Selected class does not have an active Komting yet.';
  end if;

  if v_requested_role = 'komting' and exists (
    select 1
    from public.profiles p
    where p.class_id = v_class_id
      and p.role = 'komting'::public.app_role
      and p.is_active = true
  ) then
    raise exception 'Selected class already has an active Komting.';
  end if;

  insert into public.registration_requests (user_id, requested_role, class_id)
  values (new.id, v_requested_role, v_class_id);

  return new;
end;
$$;


