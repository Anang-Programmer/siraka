  v_request_id uuid;
  v_class_is_active boolean;
begin
  if v_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  if p_requested_role is null or p_requested_role not in ('mahasiswa', 'komting') then
    raise exception 'Registration role must be mahasiswa or komting.';
  end if;

  if p_class_id is null then
    raise exception 'A class must be selected.';
