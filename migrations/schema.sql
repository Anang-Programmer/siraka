-- Name: after_booking_status_update(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.after_booking_status_update() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
begin
  insert into public.booking_status_history
    (booking_id, old_status, new_status, changed_by, note)
  values (
    new.id,
    old.status,
    new.status,
    (select auth.uid()),
    coalesce(new.rejection_reason, new.cancellation_reason,
      case when new.status = 'completed'::public.booking_status then 'Penggunaan selesai' else null end)
  );

  if new.status = 'approved'::public.booking_status then
    -- If another admin already approved a conflicting booking, the exclusion
    -- constraint rejects this UPDATE atomically. Pending requests never block.
    insert into public.room_reservations
      (room_id, booking_id, starts_at, ends_at, status)
    values
      (new.room_id, new.id, new.starts_at, new.ends_at, 'active'::public.reservation_status)
    on conflict (booking_id) do update
      set room_id = excluded.room_id,
          starts_at = excluded.starts_at,
          ends_at = excluded.ends_at,
          status = 'active'::public.reservation_status;
  elsif new.status in ('rejected'::public.booking_status, 'cancelled'::public.booking_status) then
    update public.room_reservations
    set status = 'cancelled'::public.reservation_status
    where booking_id = new.id;
  elsif new.status = 'completed'::public.booking_status then
    update public.room_reservations
    set ends_at = new.actual_ended_at,
        status = 'released'::public.reservation_status
    where booking_id = new.id;
  end if;

  return new;
end;
$$;


