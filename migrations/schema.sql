  -- saat memeriksa Admin aktif terakhir.
  perform pg_advisory_xact_lock(731992, 1);

  select p.role, p.class_id, p.is_active
  into v_role, v_class_id, v_current_active
  from public.profiles p
  where p.id = p_user_id
  for update;

  if not found then
    raise exception 'User profile not found.';
  end if;

  -- Jika status sudah sesuai, tidak perlu mengubah apa pun.
  if v_current_active = p_is_active then
    return;
  end if;

  -- Akun yang masih dalam proses pendaftaran harus melalui
  -- alur persetujuan pendaftaran, bukan aktivasi manual.
  if exists (
    select 1
    from public.registration_requests rr
    where rr.user_id = p_user_id
      and rr.status = 'pending'
  ) then
    raise exception 'This account has a pending registration request. Review the registration first.';
  end if;

  -- Validasi aktivasi ulang akun non-Admin.
  if p_is_active and v_role <> 'admin'::public.app_role then

    if v_class_id is null then
      raise exception 'Account has no assigned class and cannot be activated.';
    end if;

    select c.is_active
    into v_class_active
    from public.classes c
    where c.id = v_class_id;

    if not found or v_class_active is not true then
      raise exception 'The assigned class is inactive or unavailable.';
    end if;

    -- Satu kelas hanya boleh memiliki satu Komting aktif.
    if v_role = 'komting'::public.app_role then
      perform 1
      from public.classes c
      where c.id = v_class_id
      for update;

      if exists (
        select 1
        from public.profiles p
        where p.class_id = v_class_id
          and p.role = 'komting'::public.app_role
          and p.is_active = true
          and p.id <> p_user_id
      ) then
        raise exception 'This class already has another active Komting.';
      end if;
    end if;
  end if;

  -- Jangan sampai sistem kehilangan seluruh Admin aktif.
  if not p_is_active
     and v_role = 'admin'::public.app_role then

    select count(*)
    into v_admin_count
    from public.profiles p
    where p.role = 'admin'::public.app_role
      and p.is_active = true;

    if v_admin_count <= 1 then
      raise exception 'Cannot deactivate the last active Admin account.';
    end if;
  end if;

  update public.profiles
  set is_active = p_is_active
  where id = p_user_id;
end;
$$;


