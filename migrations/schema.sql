CREATE FUNCTION public.submit_booking(p_booking_id uuid, p_room_id uuid, p_title text, p_purpose text, p_starts_at timestamp with time zone, p_ends_at timestamp with time zone, p_activity_type text DEFAULT NULL::text, p_participant_count integer DEFAULT NULL::integer, p_is_krs_priority boolean DEFAULT false, p_krs_document_path text DEFAULT NULL::text, p_reference_code text DEFAULT NULL::text) RETURNS uuid
    LANGUAGE plpgsql SECURITY DEFINER
