-- Name: admin_review_booking(uuid, text, text, text); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.admin_review_booking(p_booking_id uuid, p_decision text, p_rejection_reason text DEFAULT NULL::text, p_krs_note text DEFAULT NULL::text) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
declare
  v_booking public.bookings%rowtype;
  v_krs_status public.krs_verification_status;
begin
  if auth.uid() is null or not (select public.is_admin()) then
    raise exception 'Only Admin can review bookings.';
  end if;

  if p_decision not in ('approved', 'rejected') then
    raise exception 'Invalid decision.';
  end if;

  if p_decision = 'rejected'
     and nullif(trim(p_rejection_reason), '') is null then
    raise exception 'Alasan penolakan wajib diisi.';
  end if;

  select *
  into v_booking
  from public.bookings
  where id = p_booking_id
  for update;

  if not found then
    raise exception 'Booking tidak ditemukan.';
  end if;

  if v_booking.status not in (
    'pending'::public.booking_status,
    'under_review'::public.booking_status
  ) then
    raise exception 'Booking ini sudah diproses.';
  end if;

  if p_decision = 'approved' then

    if v_booking.booking_type = 'krs_priority'::public.booking_type then

      select status
      into v_krs_status
      from public.krs_verifications
      where booking_id = p_booking_id
      for update;

      if not found then
        raise exception 'Dokumen KRS tidak ditemukan.';
      end if;

      if v_krs_status = 'pending'::public.krs_verification_status then
        update public.krs_verifications
        set status = 'verified',
            notes = nullif(trim(p_krs_note), '')
        where booking_id = p_booking_id;

      elsif v_krs_status <> 'verified'::public.krs_verification_status then
        raise exception 'Dokumen KRS sudah ditolak dan tidak dapat disetujui.';
      end if;
    end if;

    update public.bookings
    set status = 'approved'::public.booking_status
    where id = p_booking_id;

  else

    if v_booking.booking_type = 'krs_priority'::public.booking_type then
      update public.krs_verifications
      set status = 'rejected',
          notes = nullif(trim(p_rejection_reason), '')
      where booking_id = p_booking_id
        and status = 'pending';
    end if;

    update public.bookings
    set status = 'rejected'::public.booking_status,
        rejection_reason = trim(p_rejection_reason)
    where id = p_booking_id;

  end if;
end;
$$;


